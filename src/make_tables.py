def sci_up(x, p=1):
    """Like sci, but rounds the mantissa up: for numbers quoted as upper bounds."""
    import math
    e = math.floor(math.log10(x)); m = math.ceil(x / 10 ** e * 10 ** p - 1e-9) / 10 ** p
    if m >= 10: m, e = m / 10, e + 1
    return f"${m:.{p}f}\\times10^{{{e}}}$"


def sci(x, p=2):
    if x == 0: return "0"
    m, e = f"{x:.{p}e}".split("e")
    return f"${m}\\times10^{{{int(e)}}}$"

