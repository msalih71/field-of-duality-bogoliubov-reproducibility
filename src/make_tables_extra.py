def sci_up(x, p=1):
    """Like sci, but rounds the mantissa up: for numbers quoted as upper bounds."""
    import math
    ex = math.floor(math.log10(x)); m = math.ceil(x / 10 ** ex * 10 ** p - 1e-9) / 10 ** p
    if m >= 10: m, ex = m / 10, ex + 1
    return (f"${m:.{p}f}\\times10^{{{ex}}}$" if p else f"${m:.0f}\\times10^{{{ex}}}$")


def sci(x, p=2):
    m, e = f"{x:.{p}e}".split("e")
    return f"${m}\\times10^{{{int(e)}}}$"

